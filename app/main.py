"""FastAPI application factory.

Run locally with:
    uvicorn app.main:app --host 127.0.0.1 --port 8000
Swagger UI: http://127.0.0.1:8000/docs
"""

from __future__ import annotations

import time
import uuid
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException

from app import __version__
from app.api.routes import router
from app.core.config import Settings, enforce_local_only, get_settings
from app.core.container import ServiceContainer, build_container
from app.core.exceptions import AppError
from app.services.ollama_utils import check_ollama
from app.utils.logging_config import configure_logging, get_logger

logger = get_logger("app")

# Multipart framing adds a little overhead on top of the file itself.
_MULTIPART_OVERHEAD = 64 * 1024


def _error_response(status_code: int, code: str, message: str, request: Request, details=None) -> JSONResponse:
    body = {
        "error": {
            "code": code,
            "message": message,
            "details": details,
            "request_id": getattr(request.state, "request_id", None),
        }
    }
    return JSONResponse(status_code=status_code, content=body)


def _log_startup_diagnostics(settings: Settings) -> None:
    status = check_ollama(settings.ollama_base_url, settings.llm_model, settings.embedding_model)
    if status.reachable:
        logger.info("Ollama reachable at %s; installed models: %s", settings.ollama_base_url, ", ".join(status.installed_models) or "none")
    for hint in status.hints:
        logger.warning("STARTUP CHECK: %s", hint)
    if not status.hints:
        logger.info("Models ready: llm=%s embedding=%s", settings.llm_model, settings.embedding_model)


def create_app(settings: Settings | None = None, container: ServiceContainer | None = None) -> FastAPI:
    settings = settings or (container.settings if container else get_settings())
    enforce_local_only()
    configure_logging(settings.log_level)

    @asynccontextmanager
    async def lifespan(app: FastAPI) -> AsyncIterator[None]:
        if getattr(app.state, "container", None) is None:
            app.state.container = build_container(settings)
            _log_startup_diagnostics(settings)
        logger.info(
            "Started %s v%s | llm=%s | embedding=%s | collection=%s",
            settings.app_name,
            __version__,
            settings.llm_model,
            settings.embedding_model,
            settings.collection_name,
        )
        yield

    app = FastAPI(
        title=settings.app_name,
        version=__version__,
        description=(
            "Upload a PDF or TXT document and ask questions about it. Answers are generated by a local "
            "Ollama model from retrieved passages only, with source attribution, and the service abstains "
            "when the document does not contain the answer."
        ),
        lifespan=lifespan,
    )
    app.state.container = container
    app.include_router(router)

    @app.middleware("http")
    async def request_context(request: Request, call_next):
        request.state.request_id = uuid.uuid4().hex[:12]
        started = time.perf_counter()
        # Reject oversized uploads before the multipart body is parsed.
        if request.method == "POST" and request.url.path == "/upload":
            length = request.headers.get("content-length")
            if length and length.isdigit() and int(length) > settings.max_upload_bytes + _MULTIPART_OVERHEAD:
                response = _error_response(
                    413,
                    "FILE_TOO_LARGE",
                    f"The uploaded file exceeds the {settings.max_upload_size_mb:g} MB limit.",
                    request,
                )
                response.headers["X-Request-ID"] = request.state.request_id
                return response
        response = await call_next(request)
        response.headers["X-Request-ID"] = request.state.request_id
        logger.info(
            "%s %s -> %d in %.0f ms [request_id=%s]",
            request.method,
            request.url.path,
            response.status_code,
            (time.perf_counter() - started) * 1000,
            request.state.request_id,
        )
        return response

    @app.exception_handler(AppError)
    async def app_error_handler(request: Request, exc: AppError) -> JSONResponse:
        log = logger.error if exc.status_code >= 500 else logger.info
        log("%s (%d): %s [request_id=%s]", exc.code, exc.status_code, exc.message, getattr(request.state, "request_id", None))
        return _error_response(exc.status_code, exc.code, exc.message, request, exc.details)

    @app.exception_handler(RequestValidationError)
    async def validation_error_handler(request: Request, exc: RequestValidationError) -> JSONResponse:
        details = []
        for err in exc.errors():
            location = [str(part) for part in err.get("loc", ()) if part not in ("body", "query", "path")]
            # The rejected input value is deliberately not echoed back.
            details.append({"field": ".".join(location) or "body", "issue": err.get("msg", "invalid value")})
        return _error_response(422, "VALIDATION_ERROR", "The request is invalid.", request, details)

    @app.exception_handler(StarletteHTTPException)
    async def http_error_handler(request: Request, exc: StarletteHTTPException) -> JSONResponse:
        codes = {404: "NOT_FOUND", 405: "METHOD_NOT_ALLOWED"}
        message = exc.detail if isinstance(exc.detail, str) else "HTTP error"
        return _error_response(exc.status_code, codes.get(exc.status_code, "HTTP_ERROR"), message, request)

    @app.exception_handler(Exception)
    async def unhandled_error_handler(request: Request, exc: Exception) -> JSONResponse:
        logger.exception("Unhandled error [request_id=%s]", getattr(request.state, "request_id", None))
        return _error_response(500, "INTERNAL_ERROR", "An unexpected internal error occurred.", request)

    return app


app = create_app()
